// Cost of Thriving Index formula:
// thrivingTarget = (costOfLivingIndex / 100) * 30000 * 10  (baseline $30k NYC adjusted, times 10 for utopia)
// costOfThrivingIndex = (annualCashTransfer / thrivingTarget) * 100  (capped at 100)
// This measures what percentage of a "thriving" income the state provides

function calcThrivingTarget(colIndex: number): number {
  return (colIndex / 100) * 30000 * 10; // $300k NYC baseline * COL adjustment
}

function calcCTI(cashTransfer: number, target: number): number {
  return Math.min(100, Math.round((cashTransfer / target) * 1000) / 10);
}

